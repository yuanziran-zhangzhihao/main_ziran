static uint8_t xtime(uint8_t x){ return (uint8_t)((x<<1) ^ ((x & 0x80) ? 0x1B : 0)); }

static void AddRoundKey(uint8_t s[4][4], const uint8_t *rk){
  for(int c=0;c<4;c++) for(int r=0;r<4;r++) s[r][c] ^= rk[c*4 + r];
}
static void SubBytes(uint8_t s[4][4]){
  for(int r=0;r<4;r++) for(int c=0;c<4;c++) s[r][c] = sbox[s[r][c]];
}
static void ShiftRows(uint8_t s[4][4]){
  uint8_t t;
  t=s[1][0]; s[1][0]=s[1][1]; s[1][1]=s[1][2]; s[1][2]=s[1][3]; s[1][3]=t;
  t=s[2][0]; uint8_t t2=s[2][1]; s[2][0]=s[2][2]; s[2][1]=s[2][3]; s[2][2]=t; s[2][3]=t2;
  t=s[3][3]; s[3][3]=s[3][2]; s[3][2]=s[3][1]; s[3][1]=s[3][0]; s[3][0]=t;
}
static void MixColumns(uint8_t s[4][4]){
  for(int c=0;c<4;c++){
    uint8_t a0=s[0][c], a1=s[1][c], a2=s[2][c], a3=s[3][c];
    uint8_t m2a0=xtime(a0), m2a1=xtime(a1), m2a2=xtime(a2), m2a3=xtime(a3);
    uint8_t m3a0=(uint8_t)(m2a0 ^ a0), m3a1=(uint8_t)(m2a1 ^ a1), m3a2=(uint8_t)(m2a2 ^ a2), m3a3=(uint8_t)(m2a3 ^ a3);
    s[0][c] = (uint8_t)(m2a0 ^ m3a1 ^ a2 ^ a3);
    s[1][c] = (uint8_t)(a0 ^ m2a1 ^ m3a2 ^ a3);
    s[2][c] = (uint8_t)(a0 ^ a1 ^ m2a2 ^ m3a3);
    s[3][c] = (uint8_t)(m3a0 ^ a1 ^ a2 ^ m2a3);
  }
}

static void KeyExpansion128(const uint8_t key[16], uint8_t ek[176]){
  // ek: 11 round keys * 16 bytes
  for(int i=0;i<16;i++) ek[i] = key[i];
  uint8_t rcon = 0x01;
  int bytes = 16;

  while(bytes < 176){
    uint8_t t0=ek[bytes-4], t1=ek[bytes-3], t2=ek[bytes-2], t3=ek[bytes-1];

    if(bytes % 16 == 0){
      // RotWord
      uint8_t tmp=t0; t0=t1; t1=t2; t2=t3; t3=tmp;
      // SubWord
      t0=sbox[t0]; t1=sbox[t1]; t2=sbox[t2]; t3=sbox[t3];
      // Rcon
      t0 ^= rcon;
      rcon = xtime(rcon);
    }

    ek[bytes+0] = (uint8_t)(ek[bytes-16+0] ^ t0);
    ek[bytes+1] = (uint8_t)(ek[bytes-16+1] ^ t1);
    ek[bytes+2] = (uint8_t)(ek[bytes-16+2] ^ t2);
    ek[bytes+3] = (uint8_t)(ek[bytes-16+3] ^ t3);
    bytes += 4;
  }
}

static void AES128_EncryptBlock(const uint8_t in[16], uint8_t out[16], const uint8_t ek[176]){
  uint8_t s[4][4];
  for(int c=0;c<4;c++) for(int r=0;r<4;r++) s[r][c] = in[c*4 + r]; // column-major

  AddRoundKey(s, ek);                 // round 0
  for(int round=1; round<=9; round++){
    SubBytes(s); ShiftRows(s); MixColumns(s);
    AddRoundKey(s, ek + round*16);
  }
  SubBytes(s); ShiftRows(s);          // last round (no MixColumns)
  AddRoundKey(s, ek + 10*16);

  for(int c=0;c<4;c++) for(int r=0;r<4;r++) out[c*4 + r] = s[r][c];
}

